/** The rivalry name for a pair of schools, if they have one (the first listed wins). */
export function rivalryOf(a: string, b: string): string | null {
  const hit = RIVALRIES.find(([x, y]) => (x === a && y === b) || (x === b && y === a));
  return hit ? hit[2] : null;
}

