# Writes ../src/core/helpers68k.ts from the assembled helpers in /tmp.
out = ['// Generated by asm/build.sh from asm/*.s (m68k-linux-gnu-as -m68000). Do not edit by hand.', '']
info = {
    'menuorder': ('MENU_ORDER', 0x1F0000, {'G3': 0x2C, 'G4': 0x3A, 'ORD': 0x48, 'INV': 0x6C}),
    'endzone': ('END_ZONE', 0x1F0280, {'EZT': 0x18}),
    'helmet': ('HELMET_BASE', 0x1F0300, {}),
    'celebration': ('CELEBRATION', 0x1F0320, {'CT': 0x44}),
}
for f, (name, addr, labels) in info.items():
    b = open('/tmp/%s.bin' % f, 'rb').read()
    out.append('export const %s = {' % name)
    out.append('  addr: 0x%06X,' % addr)
    for k, v in labels.items():
        out.append('  %s: 0x%02X,' % (k, v))
    out.append('  code: Uint8Array.from([%s]),' % ', '.join('0x%02X' % x for x in b))
    out.append('};')
    out.append('')
open('../src/core/helpers68k.ts', 'w').write('\n'.join(out))
